# Regenerates R/reexports.R from the NAMESPACE files of agemodelR, ens and lipdViz.
# Run from this repo root after an export changes in any of them, then run
# devtools::document().
getExports <- function(path) {
  ns <- readLines(path)
  gsub("^export\\(|\\)$", "", grep("^export\\(", ns, value = TRUE))
}
pkgs <- c(agemodelR = "../geoChronR-chronOnly", ens = "../ens", lipdViz = "../lipdViz")
if (dir.exists("../agemodelR")) pkgs["agemodelR"] <- "../agemodelR"
block <- function(fun, pkg) {
  name <- if (grepl("^[a-zA-Z.][a-zA-Z0-9._]*$", fun)) fun else sprintf("`%s`", fun)
  c("#'", "#' @export", sprintf("%s::%s", pkg, name), "")
}
out <- c("# Re-exports: geoChronR 2.x is a wrapper that provides the full APIs of agemodelR,",
         "# ens and lipdViz, so code written against geoChronR 1.x keeps working unchanged.",
         "# GENERATED by tools/gen_reexports.R; do not edit by hand.", "")
for (p in names(pkgs)) {
  ex <- getExports(file.path(pkgs[[p]], "NAMESPACE"))
  out <- c(out, unlist(lapply(ex, block, pkg = p)))
  cat(p, length(ex), "\n")
}
writeLines(out, "R/reexports.R")
